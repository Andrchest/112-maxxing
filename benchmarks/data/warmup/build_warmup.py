"""Builds `benchmarks/data/warmup/warmup_ru.wav` — the warm-up sample every profile's
`warmup.asr_sample_path` names (`/models/warmup/warmup_ru.wav`, SPEC §37, HLD 60 §4.2). Absent on
this machine until this task (E19-F: recon §7 confirmed no `make` target and no file existed
anywhere, even though four profile YAMLs already reference the path).

Committed (R9 of the E19-F brief): calls the real `piper-tts` package directly (the same one
`backend/app/inference/tts/piper_tts.py`'s `PiperTTS` wraps — see that module's docstring for the
`PiperVoice.synthesize()` API this uses) against one short Russian sentence. `make models-warmup`
runs this, then copies the output to `models/warmup/warmup_ru.wav` (a real `cp`, not a symlink — the
Makefile's own comment explains why).

**Not byte-for-byte reproducible** (measured by this task, not assumed): VITS's noise-scale input is
generated by a `RandomNormal` op **inside the ONNX graph itself** (`PiperVoice.phoneme_ids_to_audio`
passes only `scales` — the noise array is not a Python-side input `onnxruntime` could be seeded
for through the public `piper-tts` API), so `numpy.random.seed()` below has no effect on it and two
runs of this script differ (this task measured 2.47 s vs. 2.51 s, different sha256, same seed and
text). The `SEED` constant is kept for whatever *is* numpy-side (none currently), documented rather
than silently dropped; the committed `warmup_ru.wav` is therefore a one-time build output, not
something a CI re-run is expected to reproduce exactly — only its duration budget (`MAX_DURATION_S`)
and validity as a real Piper WAV matter for its purpose (ASR warm-up).

Usage: `uv run python benchmarks/data/warmup/build_warmup.py [--voice-path PATH] [--out PATH]`
"""

from __future__ import annotations

import argparse
import wave
from pathlib import Path

import numpy as np

_REPO_ROOT = Path(__file__).resolve().parents[3]
DEFAULT_VOICE_PATH = _REPO_ROOT / "models" / "piper" / "ru_RU-irina-medium.onnx"
DEFAULT_OUT_PATH = Path(__file__).resolve().parent / "warmup_ru.wav"
# Short and generic on purpose: this is a warm-up utterance (loads the ASR model and primes its
# CUDA kernels before the first real turn), not a corpus item — R5's ASR corpus owns "several
# utterance lengths / addresses / numbers / terminology" (E19-A's benchmarks/data/asr/).
WARMUP_TEXT = "Проверка готовности перед началом смены."
SEED = 1206
MAX_DURATION_S = 3.0


def build_warmup_wav(voice_path: Path, out_path: Path) -> float:
    """Synthesizes `WARMUP_TEXT` with the Piper voice at `voice_path`, writes a 16-bit PCM mono
    WAV to `out_path`, and returns the duration in seconds. Raises if the voice files are missing
    (run `make models-piper` first) or if the result exceeds `MAX_DURATION_S` (R9)."""
    json_path = voice_path.with_suffix(voice_path.suffix + ".json")
    if not voice_path.is_file() or not json_path.is_file():
        raise FileNotFoundError(
            f"Piper voice not found: {voice_path} (+ {json_path.name}) — "
            "run `make models-piper` first"
        )

    # Best-effort only; see module docstring "Not byte-for-byte reproducible".
    np.random.seed(SEED)

    from piper import PiperVoice

    voice = PiperVoice.load(str(voice_path), str(json_path))
    pcm = b"".join(chunk.audio_int16_bytes for chunk in voice.synthesize(WARMUP_TEXT))
    sample_rate = int(voice.config.sample_rate)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(out_path), "wb") as wav_file:
        wav_file.setnchannels(1)
        wav_file.setsampwidth(2)
        wav_file.setframerate(sample_rate)
        wav_file.writeframes(pcm)

    duration_s = len(pcm) / 2 / sample_rate
    if duration_s > MAX_DURATION_S:
        raise ValueError(
            f"warm-up WAV is {duration_s:.2f}s, over the {MAX_DURATION_S}s budget (R9) — "
            "shorten WARMUP_TEXT"
        )
    return duration_s


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--voice-path", type=Path, default=DEFAULT_VOICE_PATH)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT_PATH)
    args = parser.parse_args()

    duration_s = build_warmup_wav(args.voice_path, args.out)
    print(f"wrote {args.out} ({duration_s:.2f}s, seed={SEED}, voice={args.voice_path.name})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
