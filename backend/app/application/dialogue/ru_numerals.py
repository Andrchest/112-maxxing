"""`RU_NUMERAL_LEXICON` — spelled-out Russian numerals and their canonical values (§7.2 step 4).

A **data file**, not a regex, exactly as `50-voice-pipeline.md` §7.2 asks: "so it can be extended
without touching the algorithm". The folding algorithm lives in `text_normalization.py` and reads
nothing from here but `form -> value`.

Coverage per §7.2: `ноль…девятнадцать`, the tens `двадцать…девяносто`, the hundreds `сто…девятьсот`,
`тысяча`, their case forms, the ordinals `первый…двадцатый`, and the fraction words `половина`,
`треть`, `четверть`.

Forms are given already normalised the way `text_normalization.normalize_text` normalises a token:
lower case, `ё` folded to `е`. A lookup is therefore a plain dict hit with no per-call work.
"""

